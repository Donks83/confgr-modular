// Build the commercial catalogue for the configurable YouK parts.
//
//   node tools/make-catalogue.mjs youk
//
// One entry per part the snap spec has authored: the supplier's article number,
// the supplier's own English description, the measured size - and the money,
// which starts empty and is NEVER invented.
//
// WHY A GENERATOR RATHER THAN A HAND-WRITTEN FILE
//
// The article numbers and descriptions already exist, in the STEP filenames
// Kesseboehmer sent. Retyping 22 of them is 22 chances to transpose a digit
// into a document somebody later quotes from. So they are derived from
// convert-report.json, which records the source filename for every part.
//
// RE-RUNNING MUST NOT LOSE MONEY. Any costEach, priceEach, tier markup or price
// list reference already in the file is carried over untouched; this only adds
// parts, refreshes descriptions and sizes, and reports what it kept. Anything
// else and the first price list Matt types in would be one regeneration away
// from being wiped.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

// The tiers a partnership quote actually needs: what Kesseboehmer charges the
// partner, what the partner charges a retailer, what a retailer charges the
// public. Markups are null until somebody who knows sets them - a made-up
// markup in a committed file is indistinguishable from a real one later.
const DEFAULT_TIERS = [
  { id: 'retailer', name: 'Retailer', markupOnCost: null },
  { id: 'trade', name: 'Trade', markupOnCost: null },
  { id: 'retail', name: 'Retail (RRP)', markupOnCost: null },
];

const HEADER = [
  'The commercial side of the YouK range: article numbers, descriptions, and the',
  'money. Generated by tools/make-catalogue.mjs from youk/snap-spec.json and',
  'youk/convert-report.json, and safe to regenerate - it never overwrites a',
  'price, a markup or a price-list reference that is already here.',
  '',
  'EVERY PRICE STARTS null AND null MEANS UNKNOWN, NOT FREE. src/engine/quote.js',
  'refuses to treat a missing price as zero: the line shows as unpriced and the',
  'quote reports how many lines it could not price. A quote that silently prices',
  'a missing part at nothing is worse than one that admits it cannot.',
  '',
  'Two ways to price a part, and explicit wins:',
  '  priceEach: { "<tier>": 123.45 }   a real price list, loaded verbatim',
  '  costEach + the tier markupOnCost  derived, for parts not on the list yet',
  '',
  'Fill in priceList.ref/dated/source when the numbers arrive, so a quote can',
  'say which price list it came from. Set vatRatePercent for a gross total.',
];

// Where the German half of a supplier filename starts. Splitting on the FIRST
// comma looked right and quietly threw away the frames' heights: "236746 - YouK
// Leiterregal ladder depth 200 mm, height 668 mm, Leitertiefe 200 mm, Hoehe 668
// mm" has TWO English segments, and dropping the second leaves four frames of
// different heights sharing one description on a quote.
//
// Diacritics catch most of it; the word list catches the ASCII German. Note
// that "Leiterregal" is deliberately absent - Kesseboehmer use it inside an
// English segment, so treating it as a marker would truncate 236746 again.
const GERMAN = new RegExp([
  '[äöüßÄÖÜ]',
  'Leitertiefe', 'Leiterbreite', 'Regalboden', 'Garderobenstange', 'Hakenleiste',
  'Ablage', 'Korpushalterung', 'Fachtrenner', 'Bodenträger', 'Klemmwinkel',
  'Grundhalterung', 'Abdeckbodenhalterung', 'Wanne', 'Schirmständer',
  'Zeitungs', 'Handtuchablage', 'Erweiterung', 'obere', 'untere', 'für',
].join('|'));

function describe(sourceFilename) {
  // "008563 - YouK shelf 900 mm for ladder depth 320 mm, Regalboden ... .stp"
  //  -> article "008563", description "YouK shelf 900 mm for ladder depth 320 mm"
  const stem = sourceFilename.replace(/\.(stp|step)$/i, '');
  const segments = stem.split(',').map((s) => s.trim());
  const english = [];
  for (const segment of segments) {
    if (GERMAN.test(segment)) break;
    english.push(segment);
  }
  const joined = (english.length ? english : [segments[0]]).join(', ');
  const match = joined.match(/^(\d{6})\s*-\s*(.+)$/);
  if (!match) return { article: null, description: joined };
  return { article: match[1], description: match[2].trim() };
}

function main(argv) {
  const folder = argv[0] || 'youk';
  const specPath = join(folder, 'snap-spec.json');
  const reportPath = join(folder, 'convert-report.json');
  const outPath = join(folder, 'catalogue.json');

  const spec = JSON.parse(readFileSync(specPath, 'utf8'));
  const report = JSON.parse(readFileSync(reportPath, 'utf8'));

  const sources = new Map(report.parts.map((p) => [p.id, p]));
  // EVERY family, found rather than listed. This was `spec.frames + span + hang
  // + wall`, and that spelling has now gone stale twice: once when `wall` was
  // added, which put the shoe rack in the app with a raw model id for a name and
  // no line on the quote, and again when `carcase` was, which left 24 cabinets
  // out of the catalogue entirely. A part that joins nothing is still a part
  // somebody is billed for, and so is a part that joins downwards.
  //
  // The rule instead: any array in the spec whose rows carry an id is a family.
  // Adding one to snap-spec.json is now all it takes.
  const configurable = Object.values(spec)
    .filter((value) => Array.isArray(value) && value.every((row) => row && row.id))
    .flat()
    .map((row) => row.id);

  const existing = existsSync(outPath) ? JSON.parse(readFileSync(outPath, 'utf8')) : {};
  const keptItems = existing.items || {};

  // Parts PWS makes rather than buys. They have no STEP file and never will -
  // Kesseböhmer's brochure says the wooden shelves are made by a carpenter and
  // are not in the YouK range - so convert-report.json knows nothing about them
  // and their description comes from the generator's manifest instead.
  //
  // They still belong on the quote. `supplier` is what tells a reader which is
  // which, and it is why an article number of null here is a fact rather than a
  // gap: we have not assigned one yet.
  const manifestPath = join(folder, 'timber-manifest.json');
  const manifest = existsSync(manifestPath)
    ? new Map(JSON.parse(readFileSync(manifestPath, 'utf8')).parts.map((p) => [p.id, p]))
    : new Map();

  const items = {};
  const noSource = [];
  for (const id of configurable) {
    const own = manifest.get(id);
    if (own) {
      const was = keptItems[id] || {};
      items[id] = {
        article: was.article ?? null,
        description: was.descriptionOverride || own.description,
        ...(was.descriptionOverride ? { descriptionOverride: was.descriptionOverride } : {}),
        sizeMm: own.dims_mm,
        supplier: 'PWS',
        costEach: was.costEach ?? null,
        priceEach: was.priceEach ?? {},
      };
      if (was.notes) items[id].notes = was.notes;
      continue;
    }

    const part = sources.get(id);
    if (!part) { noSource.push(id); continue; }
    const { article, description } = describe(part.source);
    const was = keptItems[id] || {};
    items[id] = {
      article,
      // A human decision beats the heuristic and must survive regeneration -
      // the supplier's filenames are inconsistent enough that some description
      // will eventually need fixing by hand, and it should stay fixed.
      description: was.descriptionOverride || description,
      ...(was.descriptionOverride ? { descriptionOverride: was.descriptionOverride } : {}),
      sizeMm: part.dims_mm,
      // Money, carried over verbatim. Note ?? rather than ||: a genuine 0 is a
      // price somebody entered, and must survive.
      costEach: was.costEach ?? null,
      priceEach: was.priceEach ?? {},
    };
    if (was.notes) items[id].notes = was.notes;
  }

  const out = {
    _: HEADER,
    currency: existing.currency || 'GBP',
    priceList: existing.priceList || { ref: null, dated: null, source: null },
    vatRatePercent: existing.vatRatePercent ?? null,
    tiers: existing.tiers || DEFAULT_TIERS,
    items,
  };

  writeFileSync(outPath, `${JSON.stringify(out, null, 2)}\n`, 'utf8');

  const priced = Object.values(items).filter(
    (i) => i.costEach != null || Object.values(i.priceEach).some((v) => v != null),
  ).length;
  const carried = Object.keys(keptItems).length;

  process.stdout.write(
    `${Object.keys(items).length} configurable parts -> ${outPath}\n`
    + `  ${priced} with a price or cost on file, ${Object.keys(items).length - priced} without\n`
    + (carried ? `  carried over money from ${carried} existing entries\n` : '')
    + (noSource.length
      ? `  ${noSource.length} in the spec but not in the convert report: ${noSource.join(', ')}\n`
      : '')
    + `  tiers: ${out.tiers.map((t) => t.id).join(', ')}\n`
    + (out.priceList.ref ? `  price list: ${out.priceList.ref}\n` : '  price list: none named yet\n'),
  );
  return noSource.length ? 1 : 0;
}

const invokedDirectly = process.argv[1] && process.argv[1].endsWith('make-catalogue.mjs');
if (invokedDirectly) process.exitCode = main(process.argv.slice(2));

export { describe, main };
