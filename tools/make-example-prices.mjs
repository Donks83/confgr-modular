// Build youk/catalogue.example.json: the real catalogue with FICTIONAL money.
//
//   node tools/make-example-prices.mjs
//
// For demos and probes, so the maths and the panel can be seen working before
// Kesseboehmer's price list exists. Point the app at it with
// CONFGR_CATALOGUE=...\youk\catalogue.example.json.
//
// The numbers are invented and the file says so in three places: the header,
// priceList.ref, and every description is left alone so nothing reads as more
// official than it is. They are also deliberately ROUND and obviously
// synthetic - derived from each part's size, at a made-up rate per kilogram of
// nothing in particular - so that anybody who finds a total in a screenshot can
// tell at a glance it was never a real price.
//
// It is generated rather than hand-written for one reason: a hand-written file
// of plausible prices is indistinguishable from a real one six months later.
// This one cannot be mistaken, and regenerating it cannot touch the real
// catalogue.

import { readFileSync, writeFileSync } from 'node:fs';

const IN = 'youk/catalogue.json';
const OUT = 'youk/catalogue.example.json';

// Invented. A frame-sized part lands near 60, a shelf near 25, a small
// accessory near 10 - the right order of magnitude for the panel to look
// realistic, and no closer to the truth than that.
const RATE_PER_LITRE = 0.9;
const FLOOR = 6;

function fakeCost([w, h, d]) {
  const litres = (w * h * d) / 1e6;
  const raw = FLOOR + litres * RATE_PER_LITRE;
  // To the nearest 50p, so every number looks like a placeholder.
  return Math.round(raw * 2) / 2;
}

const cat = JSON.parse(readFileSync(IN, 'utf8'));

cat._ = [
  '*** FICTIONAL PRICES. NOT A KESSEBOEHMER PRICE LIST. ***',
  '',
  'Generated by tools/make-example-prices.mjs so the quote panel and the',
  'pricing maths can be demonstrated before real prices exist. Every costEach',
  'here is invented from the part\'s volume at a made-up rate, rounded to 50p.',
  'The markups are invented too.',
  '',
  'Never merge these numbers into youk/catalogue.json. The app reads this file',
  'only when CONFGR_CATALOGUE points at it.',
];
cat.priceList = {
  ref: 'FICTIONAL EXAMPLE — not a real price list',
  dated: null,
  source: 'tools/make-example-prices.mjs',
};
cat.vatRatePercent = 20;
cat.tiers = [
  { id: 'retailer', name: 'Retailer', markupOnCost: 1.35 },
  { id: 'trade', name: 'Trade', markupOnCost: 1.8 },
  { id: 'retail', name: 'Retail (RRP)', markupOnCost: 2.6 },
];

let n = 0;
for (const item of Object.values(cat.items)) {
  item.costEach = fakeCost(item.sizeMm);
  item.priceEach = {};
  n += 1;
}

// One explicit price-list entry, so the "explicit beats markup" path is
// exercised by a demo as well as by a unit test.
const shelf = cat.items['008563-shelf-900mm-for-ladder-depth-320mm'];
if (shelf) shelf.priceEach = { retail: 79.95 };

writeFileSync(OUT, `${JSON.stringify(cat, null, 2)}\n`, 'utf8');
process.stdout.write(
  `${OUT}: ${n} fictional costs, tiers ${cat.tiers.map((t) => `${t.id} x${t.markupOnCost}`).join(', ')}\n`
  + '  These numbers are invented. Do not quote from them.\n',
);
